• ធ្វើកំណែទម្រង់ស៊ីជម្រៅលើវិស័យអប់រំពីបឋម ដល់ឧត្ដមសិក្សា
• វិស័យគមនាគន៍៖ ការកសាងផ្លូវថ្នល់ ផ្លូវដែក ស្ពាន កំពង់ផែ អាកាសយានដ្ឋាន
• វិស័យអប់រំ៖ កំណែទម្រង់ស៊ីជម្រៅលើវិស័យអប់រំ សាងសង់សាសារៀនបណ្ដុះបណ្ដាលធនធានមនុស្ស
• សាសនា៖ មានសុខដុមនីយកម្មខាងសាសនា
• សុខាភិបាល៖ សាង់សង់មន្ទីរពេទ្យ មណ្ឌលសុខភាព

វិស័យសេដ្ឋកិច្ច
• ទំនាក់ទំនងពាណិជ្ជកម្មអន្តរជាតិជាមួយអាស៊ាន និងមហាអំណាចពិភពលោកធំៗ
• ការរីកចម្រើនវិស័យទេសចរណ៍
• មានកំណើនទិន្នផលកសិកម្ម ឧស្សាហកម្ម កំណើនអ្នកវិនិយោគ កំណើនភ្លៀវទេសចរណ៍ មានទំនាក់ទំនងទីផ្សារក្នុងតំបន់ និងក្រៅតំបន់
• មានចម្លើយត្រឹមត្រូវផ្សេងទៀត។

IV. ព្រះរាជាណាចក្រកម្ពុជាទី២ និងការកសាងកម្ពុជាឡើងវិញមានស្ថានភាពដូចជា៖
ព្រះរាជាណាចក្រកម្ពុជាទី២
• ព្រះរាជាណាចក្រកម្ពុជាទី២ កើតឡើងតាមរយៈការបោះឆ្នោតនៅថ្ងៃទី២៣-២៨ ខែឧសភា ឆ្នាំ១៩៩៣ រៀបចំដោយអង្គការសហប្រជាជាតិ
• ការបោះឆ្នោតសកលនៅកម្ពុជាលើកទី១ ដែលបានប្រព្រឹត្តិទៅនៅឆ្នាំ១៩៩៣ ដែលរៀបចំដោយ អ៊ុនតាក់ ដែលមានប្រជាជនចូលរួមក្នុងបោះឆ្នោតប្រមាណ ៩០%
• លទ្ធផលសម្លេងឆ្នោតគណបក្ស ហ្វ៊ុន ស៊ិនប៉ិច ទទួលបាន (៥៨ អាសនៈ) គណបក្សប្រជាជនកម្ពុជាទទួលបាន (៥១អាសនៈ) គណបក្សប្រជាធិតេយ្យសេរីនិយមព្រះពុទ្ធសាសនាទទួលបាន (១០អាសនៈ) និងគណបក្សម៉ូលីណាទទួលបាន (១ អាសនៈ)
• នៅថ្ងៃទី២៤ ខែកញ្ញា ឆ្នាំ១៩៩៣ ពេលប្រកាសជាធរមាននូវបញ្ញត្តិរដ្ឋធម្មនុញ្ញនេះ ប្រទេសកម្ពុជាបានក្លាយជា ព្រះរាជាណាចក្រឡើងវិញ ដោយមានព្រះរាជាជាប្រមុខរដ្ឋ តែមិនកាន់អំណាច
• រដ្ឋាភិបាលអាណត្តិទី១ ចាប់ពីឆ្នាំ១៩៩៣ មកគឺប្រកាន់គោលនយោបាយ «រាស្រ្តមានមុនរដ្ឋ»
• បង្កើតឱ្យមានសេដ្ឋកិច្ចទីផ្សារសេរី
• ក្នុងអាណត្តិទី១ ប្រទេសកម្ពុជាមាននាយករដ្ឋមន្ត្រីពីរដឹកនាំប្រទេស ដោយនាយករដ្ឋមន្ត្រីទី១ ដឹកនាំដោយគណបក្សហ្វ៊ុន ស៊ិនប៉ិច (នរោត្តម រណឫទ្ធិ) និងនាយករដ្ឋមន្រ្តីទី២ គឺសម្តេចហ៊ុន សែន ហើយក្រសួងមហាផ្ទៃក៏មានអ្នកដឹកនាំពីររូបដែរ

ការកសាងកម្ពុជាឡើងវិញពីឆ្នាំ១៩៩៣ ដល់បច្ចុប្បន្ន
នយោបាយ
• សមិទ្ធផលខាងផ្នែកសេដ្ឋកិច្ច និងសង្គមដែលកម្ពុជាទទួលបានក្នុងការអភិវឌ្ឍប្រកបដោយសន្ដិភាព គឺបានពេញលេញបន្ទាប់ពីការអនុវត្តនយោយបាយឈ្នះ ឈ្នះ របស់សម្ដេចហ៊ុន សែន ហើយរាជរដ្ឋាភិបាលដាក់ចេញនូវយុទ្ធសាស្ដ្រ ត្រីកោណ
• យុទ្ធសាស្ដ្រចតុកោណ (បច្ចុប្បន្នយុទ្ធសាស្ត្របញ្ចកោណដំណាក់ទី១ អាណត្តិទី៧) ក្នុងការអភិវឌ្ឍសេដ្ឋកិច្ច-សង្គម តាមរយៈកំណែទម្រង់សាធារណៈវិមជ្ឈការ កំណែទម្រង់ច្បាប់ ប្រព័ន្ធតុលាការ សមភាពយេនឌ័រ ហិរញ្ញវត្ថុសាធារណៈ លុបបំបាត់អំពើពុករលួយ ការគ្រប់គ្រងធនធានធម្មជាតិ ប្រកបដោយចីរភាព
• រៀបចំការបោះឆ្នោតដោយខ្លួនឯង ប្រកបដោយជោគជ័យទៅតាមលទ្ធិប្រជាធិបតេយ្យ
• ធ្វើកំណែទម្រង់គ្រប់វិស័យ (អប់រំ សេដ្ឋកិច្ច រដ្ឋបាល តុលាការ និងកងកម្លាំងប្រដាប់អាវុធ)
• កម្ពុជាប្រកាន់យកលទ្ធិប្រជាធិបតេយ្យសេរីពហុបក្ស
• កម្ពុជាបានធ្វើជាម្ចាស់ផ្ទះព្រឹត្ដិការណ៍ស៊ីហ្គេម (សរុបមេដៃ ២៨២ មាស៨១ ប្រាក់៧៤ សំរិទ្ធ ១២៧) អាស៊ានប៉ារ៉ាហ្គេម (សុរបមេដៃ៧០ មាស០៩ ប្រាក់១៤ សំរឹទ្ធ៤៣) លើកទី៣២ ឆ្នាំ២០២៣ ដែលបានធ្វើឱ្យកម្ពុជាលេចមុខមាត់លើឆាកអន្ដរជាតិ និងដោយជោគជ័យ
• ការដោះស្រាយវិបត្តិកូវីដ-១៩ និងការចាក់វ៉ាក់សាំង
• កម្ពុជាក្លាយជាសមាជិកអាស៊ាន ធ្វើឱ្យកម្ពុជាមានភាពស្មើមុខមាត់ជាមួយបណ្ដាប្រទេសនៅក្នុងតំបន់ (៣០ មេសា ១៩៩៩)
• កម្ពុជាបានក្លាយជាសមាជិកអង្គការពាណិជ្ជកម្មពិភពលោកឆ្នាំ២០០៤ (WTO) និងអង្គការនានា
• ចូលរួមថែរក្សាសន្ដិភាពពិភពលោក (កងទ័ពមួកខៀវ)
• ធ្វើជាម្ចាស់ផ្ទះក្នុងកិច្ចប្រជុំអាស៊ានចំនួន ០៣លើក (២០០២,២០១២, ២០២២)

វិស័យសេដ្ឋកិច្ច
• បង្កើនទំនាក់ទំនងពាណិជ្ជកម្មអន្ដរជាតិជាមួយអាស៊ាន និងមហាអំណាចធំៗលើពិភពលោក
• កសិកម្មមានការរីកចម្រើន ដោយរដ្ឋាភិបាលបានយកចិត្ដទុកដាក់ក្នុងការបង្កើតប្រព័ន្ធធារាសាស្ដ្រ ការបង្កាត់ពូជ ការប្រើប្រាស់ជី
• អនុវត្តសេដ្ឋកិច្ចទីផ្សារសេរី កម្ពុជាក្លាយជាកន្លែងវិនិយោគទុនដ៏ទាក់ទាញ
• ជំរុញ និងលើកទឹកចិត្ដការវិនិយោគពីឯកជន បង្កើនទុនពីបរទេស
• ជំរុញឱ្យមានការយកចិត្ដទុកដាក់លើវិស័យទេសចរណ៍ វប្បធម៌ និងទេសចរណ៍ធម្មជាតិសម្រាប់ទាក់ទាញភ្លៀវ ជាតិ និងអន្ដរជាតិ
• ធ្វើឱ្យអត្រាប្ដូរប្រាក់មានស្ថិរភាព
• បង្កើនទំនាក់ទំនងពាណិជ្ជកម្មអន្ដរជាតិជាមួយអាស៊ាន និងមហាអំណាចធំៗលើពិភពលោក
• អនុវត្តសេដ្ឋកិច្ចទីផ្សារសេរី កម្ពុជាក្លាយជាកន្លែងវិនិយោគទុនដ៏ទាក់ទាញ
• ជំរុញឧស្សាហកម្មឱ្យមានការរីកចម្រើនផ្នែករោងចក្រសហគ្រាសតូចធំជាច្រើន ពិសេសរោងចក្រវាយនភណ្ឌសម្រាប់ បង្កើនការងារដល់ប្រជាពលរដ្ឋ ហើយជៀសវាងការធ្វើចំណាកស្រុក និងកាត់បន្ថយភាពក្រីក្រ
• ជំរុញឱ្យមានការយកចិត្ដទុកដាក់លើវិស័យទេសចរណ៍ វប្បធម៌ និងទេសចរណ៍ធម្មជាតិសម្រាប់ទាក់ទាញភ្លៀវ ជាតិ និងអន្ដរជាតិ
• ចូលជាសមាជិកអង្គការពាណិជ្ជកម្មពិភពលោក (២០០៤) និងអង្គការនានា

វិស័យសង្គម
• ឆ្នាំ១៩៩៣ ដល់បច្ចុប្បន្នរាជរដ្ឋាភិបាលបានរៀបចំសណ្ដាប់ធ្នាប់សង្គម រក្សាសន្ដិសុខសុវត្ថិភាព និងសន្ដិភាពពេញលេញ
